/**
 * Export catalog tables from a SOURCE Postgres (e.g. production Supabase) to INSERT SQL.
 * Does NOT export customers, quotes, quote_items, users, profiles, tokens — use
 * supabase/sql/fresh_transactional_reset.sql on the target after import if needed.
 *
 * Requires: EXPORT_SOURCE_DATABASE_URL in .env.local (recommended), or DATABASE_URL.
 * Output:  supabase/seeds/catalog_from_source.sql (override with OUT=path)
 *
 * Usage:
 *   EXPORT_SOURCE_DATABASE_URL="postgresql://postgres.[ref]:[pw]@...pooler.supabase.com:6543/postgres" node scripts/export-catalog-to-sql.js
 *
 * Then in NEW Supabase SQL Editor: paste/run the generated file (after schema migrations).
 */
const fs = require('fs')
const path = require('path')

const root = process.cwd()
const envPath = path.join(root, '.env.local')
if (fs.existsSync(envPath)) {
  const content = fs.readFileSync(envPath, 'utf8')
  content.split(/\r?\n/).forEach((line) => {
    const trimmed = line.trim()
    const m = trimmed.match(/^([^#=]+)=(.*)$/)
    if (m) process.env[m[1].trim()] = m[2].trim()
  })
}

const url =
  process.env.EXPORT_SOURCE_DATABASE_URL ||
  process.env.SOURCE_DATABASE_URL ||
  process.env.DATABASE_URL
if (!url) {
  console.error(
    'Set EXPORT_SOURCE_DATABASE_URL (production) in .env.local, or pass via env var.'
  )
  process.exit(1)
}
if (!process.env.EXPORT_SOURCE_DATABASE_URL && process.env.DATABASE_URL) {
  console.warn(
    'Warning: using DATABASE_URL. Prefer EXPORT_SOURCE_DATABASE_URL so you do not export from the wrong DB.'
  )
}

const outPath =
  process.env.OUT ||
  path.join(root, 'supabase', 'seeds', 'catalog_from_source.sql')

function sqlString(v) {
  if (v === null || v === undefined) return 'NULL'
  return "'" + String(v).replace(/'/g, "''") + "'"
}

function sqlNum(v) {
  if (v === null || v === undefined) return 'NULL'
  if (typeof v === 'object' && v !== null && typeof v.toString === 'function') {
    const s = v.toString()
    if (s && !Number.isNaN(Number(s))) return s
  }
  const n = Number(v)
  if (Number.isNaN(n)) return 'NULL'
  return String(n)
}

function chunk(arr, size) {
  const out = []
  for (let i = 0; i < arr.length; i += size) out.push(arr.slice(i, i + size))
  return out
}

async function main() {
  const pg = await import('pg')
  const client = new pg.default.Client({ connectionString: url })
  await client.connect()

  const lines = []
  lines.push('-- Generated by scripts/export-catalog-to-sql.js — catalog only.')
  lines.push('-- Apply on NEW project after schema migrations (e.g. handover).')
  lines.push('BEGIN;')
  lines.push('')
  lines.push('-- Remove transactional rows first so product FKs are free (safe on fresh DB).')
  lines.push('DELETE FROM public.quote_items;')
  lines.push('DELETE FROM public.quotes;')
  lines.push('DELETE FROM public.customers;')
  lines.push('')
  lines.push('DELETE FROM public.roller_pricing_grid;')
  lines.push('DELETE FROM public.costing_rules;')
  lines.push('DELETE FROM public.products;')
  lines.push('DELETE FROM public.drops;')
  lines.push('DELETE FROM public.widths;')
  lines.push('DELETE FROM public.fabric_groups;')
  lines.push('')

  const tables = [
    {
      name: 'fabric_groups',
      cols: ['id', 'group_number'],
      order: 'ORDER BY id',
    },
    { name: 'widths', cols: ['id', 'width_value'], order: 'ORDER BY id' },
    { name: 'drops', cols: ['id', 'drop_value'], order: 'ORDER BY id' },
    {
      name: 'products',
      cols: ['id', 'name', 'pricing_type'],
      order: 'ORDER BY id',
    },
    {
      name: 'roller_pricing_grid',
      cols: ['id', 'fabric_group_id', 'width_id', 'drop_id', 'base_price'],
      order: 'ORDER BY id',
    },
    {
      name: 'costing_rules',
      cols: ['id', 'product_id', 'rule_name', 'rule_type', 'value'],
      order: 'ORDER BY id',
    },
  ]

  for (const t of tables) {
    const colList = t.cols.join(', ')
    const { rows } = await client.query(
      `SELECT ${colList} FROM public.${t.name} ${t.order}`
    )
    lines.push(`-- ${t.name} (${rows.length} rows)`)
    const valueRows = rows.map((r) => {
      const vals = t.cols.map((c) => {
        const v = r[c]
        if (c === 'name' || c === 'rule_name' || c === 'rule_type' || c === 'pricing_type')
          return sqlString(v)
        if (
          c === 'base_price' ||
          c === 'value' ||
          c === 'group_number' ||
          c === 'width_value' ||
          c === 'drop_value'
        )
          return sqlNum(v)
        return sqlNum(v)
      })
      return `(${vals.join(', ')})`
    })
    for (const part of chunk(valueRows, 200)) {
      lines.push(
        `INSERT INTO public.${t.name} (${colList}) VALUES\n  ${part.join(',\n  ')};`
      )
    }
    lines.push('')
  }

  lines.push('-- Align sequences')
  for (const table of [
    'fabric_groups',
    'widths',
    'drops',
    'products',
    'roller_pricing_grid',
    'costing_rules',
  ]) {
    lines.push(`SELECT setval(`)
    lines.push(`  pg_get_serial_sequence('public.${table}', 'id'),`)
    lines.push(`  (SELECT COALESCE(MAX(id), 1) FROM public.${table})`)
    lines.push(`);`)
  }
  lines.push('')
  lines.push('COMMIT;')

  await client.end()

  fs.mkdirSync(path.dirname(outPath), { recursive: true })
  fs.writeFileSync(outPath, lines.join('\n') + '\n', 'utf8')
  console.log('Wrote', outPath, `(${lines.length} lines)`)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
